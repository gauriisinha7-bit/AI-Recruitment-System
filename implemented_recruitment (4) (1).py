import re

def extract_section(text, section_names):

    lines = text.split("\n")

    extracted_lines = []

    capture = False

    for line in lines:

        current_line = line.strip()

        if not current_line:
            continue

        current_lower = current_line.lower()

        if any(section.lower() in current_lower for section in section_names):

            capture = True
            continue


        if capture:

            if re.match(
                r'^(education|experience|projects|project|certifications|certification|responsibilities|employment|summary|profile|objective|achievements|languages|interests)\b',
                current_lower
            ):
                break

            extracted_lines.append(current_line)

    return extracted_lines

