from sklearn.metrics.pairwise import cosine_similarity

def semantic_skill_matching(candidate_skills,
                            required_skills,
                            model):

    matched_skills = []

    missing_skills = []

    similarity_scores = []

    if len(candidate_skills) == 0:

        return matched_skills, missing_skills, 0

    candidate_embeddings = model.encode(
        candidate_skills,
        convert_to_tensor=False
    )

    required_embeddings = model.encode(
        required_skills,
        convert_to_tensor=False
    )

    for i, required_skill in enumerate(required_skills):

        similarities = cosine_similarity(
            [required_embeddings[i]],
            candidate_embeddings
        )[0]

        best_score = max(similarities)

        best_index = similarities.argmax()

        if best_score >= 0.60:

            matched_skills.append({

                "Required Skill": required_skill,

                "Matched Skill": candidate_skills[best_index],

                "Similarity": round(float(best_score),3)

            })

            similarity_scores.append(best_score)

        else:

            missing_skills.append(required_skill)

    if len(required_skills) == 0:

        overall_score = 0

    else:

        overall_score = round(
            (len(matched_skills) / len(required_skills)) * 100,
            2
        )

    return matched_skills, missing_skills, overall_score


